// Example: load the condition named in the URL (?condition=<id>) and the menu data.
// Put the 2_website_data folder in your app's public/ folder as /data
// (e.g. public/data/index.json, public/data/conditions/<id>.json).

import type { Category, Condition, ConditionIndexEntry, Decision } from "./types";

const BASE = "/data";

export async function loadIndex(): Promise<ConditionIndexEntry[]> {
  return (await fetch(`${BASE}/index.json`)).json();
}

export async function loadCategories(): Promise<Category[]> {
  return (await fetch(`${BASE}/categories.json`)).json();
}

export async function loadCondition(id: string): Promise<Condition | null> {
  if (!/^[a-z0-9-]+$/.test(id)) return null;           // ids are slugs only
  const res = await fetch(`${BASE}/conditions/${id}.json`);
  return res.ok ? res.json() : null;
}

// ?condition=abdomen-and-viscera-and-anus-conditions
export async function conditionFromUrl(): Promise<Condition | null> {
  const id = new URLSearchParams(window.location.search).get("condition");
  return id ? loadCondition(id) : null;
}

// Search names + aliases (e.g. "hepatitis" finds "Abdomen and Viscera and Anus Conditions")
export function search(index: ConditionIndexEntry[], q: string): ConditionIndexEntry[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return index.filter(
    (c) => c.name.toLowerCase().includes(s) || c.aliases.some((a) => a.toLowerCase().includes(s)),
  );
}

