"""Unit tests for the record/result contract and the published JSON schema."""

import json
from dataclasses import replace
from pathlib import Path

import jsonschema
import pytest

from ame_parser.models import (
    Disposition,
    GuidanceRecord,
    ParseResult,
    Requirement,
    RequirementKind,
    SourceReference,
)
from ame_parser.schema import JSON_SCHEMA, validate_record, validate_result
from ame_parser.serialization import dumps, write


ROOT = Path(__file__).parents[1]
GUIDANCE = ROOT / "src" / "data" / "guidance"


def record(**overrides) -> GuidanceRecord:
    base = GuidanceRecord(
        record_id="ame-guide-test-a-p1",
        condition="TEST CONDITION",
        scenario="A. Stable",
        disposition=Disposition.ISSUE,
        raw_disposition="ISSUE",
        source=SourceReference(document="ame_guide.pdf", pdf_page=1),
        requirements=(Requirement("Current physician report", RequirementKind.DOCUMENT),),
        raw_text="A. Stable\nCurrent physician report\nISSUE",
    )
    return replace(base, **overrides)


def result(*records: GuidanceRecord, **overrides) -> ParseResult:
    base = ParseResult(source_document="ame_guide.pdf", records=records, pages_processed=1)
    return replace(base, **overrides)


def test_valid_record_has_no_errors() -> None:
    assert validate_record(record()) == ()


@pytest.mark.parametrize(
    ("overrides", "message"),
    [
        ({"record_id": ""}, "record_id is required"),
        ({"condition": ""}, "condition is required"),
        ({"condition": "UNKNOWN"}, "condition is required"),
        ({"scenario": ""}, "scenario is required"),
        ({"raw_text": ""}, "raw_text is required"),
        (
            {"source": SourceReference(document="ame_guide.pdf", pdf_page=0)},
            "pdf_page must be positive",
        ),
    ],
)
def test_invalid_record_fields_are_reported(overrides: dict, message: str) -> None:
    errors = validate_record(record(**overrides))
    assert any(message in error for error in errors), errors


def test_unsupported_disposition_is_reported() -> None:
    class FakeDisposition:
        value = "MAYBE"

    errors = validate_record(record(disposition=FakeDisposition()))
    assert errors == ("ame-guide-test-a-p1: unsupported disposition",)


def test_valid_result_has_no_errors() -> None:
    assert validate_result(result(record())) == ()


def test_result_level_errors() -> None:
    errors = validate_result(
        result(schema_version="0.9", source_document="", pages_processed=-1)
    )
    assert "Unsupported schema version: 0.9" in errors
    assert "source_document is required" in errors
    assert "pages_processed cannot be negative" in errors


def test_duplicate_record_ids_are_reported() -> None:
    errors = validate_result(result(record(), record()))
    assert errors == ("Duplicate record_id: ame-guide-test-a-p1",)


def test_serialized_result_matches_json_schema(tmp_path: Path) -> None:
    payload = json.loads(dumps(result(record())))
    jsonschema.validate(payload, JSON_SCHEMA)
    assert payload["records"][0]["disposition"] == "ISSUE"
    assert payload["records"][0]["requirements"] == [
        {
            "kind": "DOCUMENT",
            "required": True,
            "role": "bring_list",
            "text": "Current physician report",
        }
    ]

    output = tmp_path / "nested" / "out.json"
    write(result(record()), output)
    assert json.loads(output.read_text(encoding="utf-8")) == payload


def test_published_schema_file_matches_code() -> None:
    """schemas/ame-parser-v1.schema.json is generated by `ame-parser --schema`."""

    published = json.loads(
        (ROOT / "schemas" / "ame-parser-v1.schema.json").read_text(encoding="utf-8")
    )
    assert published == JSON_SCHEMA, (
        "Schema drift: run `python -m ame_parser --schema schemas/ame-parser-v1.schema.json`"
    )


@pytest.mark.parametrize(
    "path", sorted(GUIDANCE.glob("*.normalized.json")), ids=lambda path: path.name
)
def test_committed_guidance_data_matches_contract(path: Path) -> None:
    """The JSON the web app ships must satisfy the parser contract."""

    payload = json.loads(path.read_text(encoding="utf-8"))
    jsonschema.validate(payload, JSON_SCHEMA)
    ids = [item["record_id"] for item in payload["records"]]
    assert len(ids) == len(set(ids))
